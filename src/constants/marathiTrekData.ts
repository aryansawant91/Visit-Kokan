/**
 * Helper to match any trek slug or name against curated Marathi content
 */
export function getMarathiTrek(slugOrName: string): MarathiTrekContent | null {
  if (!slugOrName) return null;
  const lower = slugOrName.toLowerCase();
  for (const [key, val] of Object.entries(MARATHI_TREKS)) {
    if (lower.includes(key) || key.includes(lower)) {
      return val;
    }
  }
  // Try matching by fort name
  if (lower.includes("torna") || lower.includes("prachandagad")) return MARATHI_TREKS["torna-fort-trek"];
  if (lower.includes("raigad")) return MARATHI_TREKS["raigad-fort-heritage-climb"];
  if (lower.includes("harishchandra") || lower.includes("kokan kada")) return MARATHI_TREKS["harishchandragad-trek"];
  if (lower.includes("kalavantin")) return MARATHI_TREKS["kalavantin-durg-trek"];
  if (lower.includes("sudhagad") || lower.includes("bhorapgad")) return MARATHI_TREKS["sudhagad-fort-trek"];
  return null;
}
