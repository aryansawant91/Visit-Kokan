/**
 * Helper to match any trek slug or name against curated Marathi content
 */
export function getMarathiTrek(slugOrName: string): MarathiTrekContent | null {
  if (!slugOrName) return null;
  const lower = slugOrName.toLowerCase();
  for (const [key, val] of Object.entries(MARATHI_TREKS)) {
    if (lower.includes(key) || key.includes(lower)) {
      return val;
    }
  }
  // Try matching by keyword / fort name
  if (lower.includes("torna") || lower.includes("prachandagad")) return MARATHI_TREKS["torna-fort-trek"];
  if (lower.includes("raigad")) return MARATHI_TREKS["raigad-fort-heritage-climb"];
  if (lower.includes("harishchandra") || lower.includes("kokan kada")) return MARATHI_TREKS["harishchandragad-trek"];
  if (lower.includes("kalavantin")) return MARATHI_TREKS["kalavantin-durg-trek"];
  if (lower.includes("sudhagad") || lower.includes("bhorapgad")) return MARATHI_TREKS["sudhagad-fort-trek"];
  if (lower.includes("rajgad")) return MARATHI_TREKS["rajgad-fort-trek"];
  if (lower.includes("kalsubai")) return MARATHI_TREKS["kalsubai-peak-trek"];
  if (lower.includes("pratapgad")) return MARATHI_TREKS["pratapgad-fort-trek"];
  if (lower.includes("lohagad")) return MARATHI_TREKS["lohagad-fort-trek"];
  if (lower.includes("ratangad")) return MARATHI_TREKS["ratangad-fort-trek"];
  if (lower.includes("shivneri")) return MARATHI_TREKS["shivneri-fort-trek"];
  if (lower.includes("visapur")) return MARATHI_TREKS["visapur-fort-trek"];
  if (lower.includes("janjira") || lower.includes("murud")) return MARATHI_TREKS["murud-janjira-sea-fortress"];
  if (lower.includes("vijaydurg")) return MARATHI_TREKS["vijaydurg-coastal-cliff-walk"];
  if (lower.includes("sindhudurg")) return MARATHI_TREKS["sindhudurg-sea-wall-trek"];
  if (lower.includes("devkund")) return MARATHI_TREKS["devkund-waterfall-trek"];
  if (lower.includes("sandhan")) return MARATHI_TREKS["sandhan-valley-trek"];
  return null;
}
